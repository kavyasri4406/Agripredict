export function getLocalizedScheme(scheme: SchemeItem, lang: Language): SchemeItem {
  if (lang === "en" || !lang) return scheme;
  
  const loc = SCHEME_LOCALIZATIONS[scheme.id]?.[lang];
  const localizedCategory = (CATEGORY_TRANSLATIONS[scheme.category]?.[lang] as any) || scheme.category;
  const localizedCoverage = STATE_TRANSLATIONS[scheme.coverage]?.[lang] || scheme.coverage;

  if (!loc) {
    return {
      ...scheme,
      category: localizedCategory,
      coverage: localizedCoverage
    };
  }

  return {
    ...scheme,
    title: loc.title || scheme.title,
    description: loc.description || loc.desc || scheme.description,
    benefit: loc.benefit || scheme.benefit,
    category: localizedCategory,
    coverage: localizedCoverage
  };
}
